def shade_paragraph(paragraph, fill: str) -> None:
    p_pr = paragraph._p.get_or_add_pPr()
    shd = p_pr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        p_pr.append(shd)
    shd.set(qn("w:fill"), fill)


def add_code_block(doc: Document, code: str) -> None:
    paragraph = doc.add_paragraph()
    paragraph.paragraph_format.left_indent = Inches(0.08)
    paragraph.paragraph_format.right_indent = Inches(0.08)
    paragraph.paragraph_format.space_before = Pt(4)
    paragraph.paragraph_format.space_after = Pt(8)
    paragraph.paragraph_format.line_spacing = 1.0
    paragraph.paragraph_format.keep_together = True
    shade_paragraph(paragraph, COLOR_CODE_FILL)
    lines = code.strip("\n").splitlines()
    for index, line in enumerate(lines):
        run = paragraph.add_run(line)
        set_run_font(run, name=FONT_CODE, size=8.2, color="24292F")
        if index < len(lines) - 1:
            run.add_break()


def add_code_comparison(doc: Document, left_code: str, right_code: str) -> None:
    table = doc.add_table(rows=2, cols=2)
    set_table_geometry(table, [4680, 4680])
    set_table_borders(table)
    headers = ("dplyr", "data.table")
    for index, label in enumerate(headers):
        cell = table.rows[0].cells[index]
        set_cell_shading(cell, COLOR_LIGHT_GRAY)
        p = cell.paragraphs[0]
        p.paragraph_format.space_after = Pt(0)
        set_run_font(p.add_run(label), size=10, color=COLOR_NAVY, bold=True)
    for index, code in enumerate((left_code, right_code)):
        cell = table.rows[1].cells[index]
        set_cell_shading(cell, COLOR_CODE_FILL)
        p = cell.paragraphs[0]
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.line_spacing = 1.0
        for line_number, line in enumerate(code.strip().splitlines()):
            run = p.add_run(line)
            set_run_font(run, name=FONT_CODE, size=7.6, color="24292F")
            if line_number < len(code.strip().splitlines()) - 1:
                run.add_break()


def read_csv_rows(filename: str) -> list[dict[str, str]]:
    with (TABLE_DIR / filename).open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def add_table_caption(doc: Document, text: str) -> None:
    caption = doc.add_paragraph(style="Caption")
    caption.add_run(text)


def add_data_table(
    doc: Document,
    headers: list[str],
    rows: list[list[str]],
    widths_dxa: list[int],
    alignments: list[int] | None = None,
) -> None:
    table = doc.add_table(rows=1, cols=len(headers))
    set_table_geometry(table, widths_dxa)
    set_table_borders(table)
    header_row = table.rows[0]
    set_repeat_table_header(header_row)
    for i, header in enumerate(headers):
        cell = header_row.cells[i]
        set_cell_shading(cell, COLOR_LIGHT_GRAY)
        p = cell.paragraphs[0]
        p.alignment = alignments[i] if alignments else WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.space_after = Pt(0)
        set_run_font(p.add_run(header), size=9, color=COLOR_NAVY, bold=True)

    for row_values in rows:
        cells = table.add_row().cells
        for i, value in enumerate(row_values):
            p = cells[i].paragraphs[0]
            p.alignment = alignments[i] if alignments else WD_ALIGN_PARAGRAPH.LEFT
            p.paragraph_format.space_after = Pt(0)
            set_run_font(p.add_run(value), size=8.8)
    set_table_geometry(table, widths_dxa)


def add_figure(doc: Document, filename: str, caption: str) -> None:
    add_table_caption(doc, caption)
